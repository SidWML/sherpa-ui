"use client";
import { Textarea } from "@/components/form";
import { useState } from "react";
import { useApp } from "@/lib/store";
import { DR, REWRITES, draftView, type DocRef, type DocSection, type DraftView, type Tip } from "@/lib/drafts";
import { Btn, Card, Icon, ago } from "../ui";

export function printDraft(v: DraftView, head: [string, string][], foot?: string) {
  const w = window.open("", "_blank"); if (!w) return;
  const esc = (x: string) => x.replace(/[&<>"]/g, (c) => ({ "&": "&amp;", "<": "&lt;", ">": "&gt;", '"': "&quot;" })[c]!);
  const para = (x: string) => esc(x).split(/\n/).join("<br>");
  w.document.write(`<!doctype html><html><head><meta charset="utf-8"><title>${esc(v.title)}</title><style>body{font:14px/1.6 system-ui,sans-serif;max-width:720px;margin:40px auto;color:#111}h1{font-size:22px}h2{font-size:15px;margin:22px 0 4px}table{width:100%;border-collapse:collapse}td{border-top:1px solid #ddd;padding:6px 4px}td:first-child{color:#666;width:35%}</style></head><body><p>Schindler India · Telangana</p><h1>${esc(v.title)}</h1><table>${head.map(([k, x]) => `<tr><td>${esc(k)}</td><td>${esc(x)}</td></tr>`).join("")}</table>${v.sections.map((x) => `<h2>${esc(x.title)}</h2><p>${para(x.text)}</p>`).join("")}${foot ?? ""}<p style="color:#666">Demo document generated by SHERPA.</p></body></html>`);
  w.document.close(); w.focus(); w.print();
}

/** The draft as one document, edited in place, with SHERPA's review beside it. */
export function DraftEditor({ docRef, canEdit, canComment = canEdit, label = "The draft", note, live }: { docRef: DocRef; canEdit: boolean; canComment?: boolean; label?: string; note?: string; live?: { discountPct?: number } }) {
  const { s, me, mutate, now } = useApp();
  const v = draftView(s, docRef, live);
  const [open, setOpen] = useState<string | null>(null);
  const [val, setVal] = useState("");
  const [talk, setTalk] = useState<{ key: string; text: string } | null>(null);
  const [glow, setGlow] = useState<string | null>(null);
  if (!v) return null;
  const by = me!.id;
  const risks = v.tips.filter((t) => t.level === "risk").length; const fixable = v.tips.filter((t) => t.fix);
  const tipsOf = (key: string) => v.tips.filter((t) => t.section === key);
  const openComments = v.comments.filter((c) => !c.resolved);
  const go = (key: string) => { setGlow(key); document.getElementById(`sec-${docRef.id}-${key}`)?.scrollIntoView({ behavior: "smooth", block: "center" }); setTimeout(() => setGlow(null), 1600); };
  const startEdit = (x: DocSection) => { setOpen(x.key); setVal(x.text); };
  const save = (key: string) => { const t = val; mutate((st) => DR.edit(st, docRef, by, key, t)); setOpen(null); };

  return (
    <section id={`draft-${docRef.id}`} className="grid grid-cols-1 items-start gap-4 @3xl:grid-cols-[1fr_18rem]">
      <Card className="overflow-hidden">
        <div className="flex flex-wrap items-center justify-between gap-2 border-b border-line bg-surface/60 px-5 py-3">
          <div><div className="t-label">{label}</div><div className="text-[12.5px] text-muted">{note ?? (canEdit ? "Click a section to change it. SHERPA keeps the rest in step with the price and scope." : "Read only for you. You can still comment.")}</div></div>
          {openComments.length > 0 && <span className="rounded-full bg-sky-50 px-2.5 py-1 text-[11.5px] font-semibold text-sky-700">{openComments.length} open comment{openComments.length > 1 ? "s" : ""}</span>}
        </div>
        <div className="space-y-1 px-3 py-4 @2xl:px-6">
          <h3 className="px-2 pb-2 text-[17px] font-semibold">{v.title}</h3>
          {v.sections.map((x) => {
            const tips = tipsOf(x.key); const cms = v.comments.filter((c) => c.section === x.key); const editing = open === x.key;
            return (
              <div key={x.key} id={`sec-${docRef.id}-${x.key}`} className={`group rounded-xl border px-3 py-2.5 transition ${glow === x.key ? "border-brand ring-4 ring-brand/15" : tips.length ? "border-amber-200 bg-amber-50/40" : "border-transparent hover:border-line"}`}>
                <div className="flex items-center justify-between gap-2">
                  <div className="flex flex-wrap items-center gap-x-2 gap-y-1 text-[12px] font-semibold uppercase tracking-[.06em] text-muted">{x.title}
                    {x.live && <span className="rounded bg-zinc-100 px-1.5 py-0.5 text-[10.5px] normal-case tracking-normal">from the offer</span>}
                    {x.editedBy && <span className="rounded bg-sky-50 px-1.5 py-0.5 text-[10.5px] normal-case tracking-normal text-sky-700">edited by {x.editedBy}</span>}
                    {tips.length > 0 && <span className="text-amber-600"><Icon n="warn" s={13} /></span>}
                  </div>
                  {!editing && (
                    <div className="flex items-center gap-2 text-[12px] font-semibold text-brand opacity-100 @2xl:opacity-0 @2xl:group-hover:opacity-100 @2xl:group-focus-within:opacity-100">
                      {canEdit && !x.live && <button onClick={() => startEdit(x)}>Edit</button>}
                      {canEdit && !x.live && <RewriteMenu onPick={(m) => mutate((st) => DR.rewrite(st, docRef, by, x.key, m))} />}
                      {canEdit && x.editedBy && <button onClick={() => mutate((st) => DR.reset(st, docRef, by, x.key))} className="text-muted">Reset</button>}
                      {canComment && <button onClick={() => setTalk({ key: x.key, text: "" })}>Comment</button>}
                    </div>
                  )}
                </div>
                {editing ? (
                  <div className="mt-2">
                    <Textarea value={val} onChange={(e) => setVal(e.target.value)} aria-label={x.title} className="min-h-28 leading-relaxed" autoFocus />
                    <div className="mt-2 flex gap-2"><Btn sm onClick={() => save(x.key)}>Save</Btn><Btn sm v="ghost" onClick={() => setOpen(null)}>Cancel</Btn></div>
                  </div>
                ) : (
                  <p onClick={() => canEdit && !x.live && startEdit(x)} className={`mt-1 whitespace-pre-line text-[14px] leading-relaxed ${canEdit && !x.live ? "cursor-text" : ""}`}>{x.text}</p>
                )}
                {cms.map((c) => (
                  <div key={c.id} className={`mt-2 flex items-start gap-2 rounded-lg px-3 py-2 text-[13px] ${c.resolved ? "bg-surface text-muted line-through" : "bg-sky-50 text-sky-950"}`}>
                    <Icon n="user" s={14} /><span className="flex-1"><b>{c.by}</b> {c.text}<span className="block text-[11px] text-muted no-underline">{ago(now - c.at)}</span></span>
                    {!c.resolved && (canEdit || canComment) && <button onClick={() => mutate((st) => DR.resolve(st, docRef, by, c.id))} className="text-[12px] font-semibold text-sky-700">Resolve</button>}
                  </div>
                ))}
                {talk?.key === x.key && (
                  <form onSubmit={(e) => { e.preventDefault(); const t = talk.text; mutate((st) => DR.comment(st, docRef, by, x.key, t)); setTalk(null); }} className="mt-2 flex gap-2">
                    <input value={talk.text} onChange={(e) => setTalk({ key: x.key, text: e.target.value })} placeholder="Your comment" aria-label={`Comment on ${x.title}`} autoFocus className="h-9 min-w-0 flex-1 rounded-md border border-line px-3 text-[13px]" />
                    <Btn sm type="submit" disabled={!talk.text.trim()}>Add</Btn><Btn sm v="ghost" onClick={() => setTalk(null)}>Cancel</Btn>
                  </form>
                )}
              </div>
            );
          })}
        </div>
      </Card>

      <Card className="p-4 @3xl:sticky @3xl:top-4">
        <div className="flex items-center gap-1.5 text-[11px] font-semibold uppercase tracking-[.08em] text-brand"><Icon n="sparkle" s={13} /> SHERPA review</div>
        {v.tips.length === 0 ? (
          <div className="mt-3 flex items-start gap-2 rounded-xl bg-emerald-50 p-3 text-[13px] text-emerald-900"><Icon n="check" s={15} /><span><b>Looks ready.</b> Nothing to fix. Read it once more before it goes out.</span></div>
        ) : (
          <>
            <p className="mt-2 text-[13px] text-muted">{risks ? `${risks} risk${risks > 1 ? "s" : ""}` : "No risks"}{v.tips.length - risks ? ` · ${v.tips.length - risks} improvement${v.tips.length - risks > 1 ? "s" : ""}` : ""}</p>
            <ul className="mt-3 space-y-2.5">{v.tips.map((t) => <TipRow key={t.id} t={t} canEdit={canEdit} go={go} apply={() => mutate((st) => DR.apply(st, docRef, by, t.id))} dismiss={() => mutate((st) => DR.dismiss(st, docRef, by, t.id))} />)}</ul>
            {canEdit && fixable.length > 1 && <Btn full sm v="soft" className="mt-3" onClick={() => mutate((st) => fixable.forEach((t) => DR.apply(st, docRef, by, t.id)))}><Icon n="sparkle" s={13} /> Apply all {fixable.length} fixes</Btn>}
          </>
        )}
        {v.log.length > 0 && (
          <details className="mt-4 border-t border-line pt-3 text-[12.5px]">
            <summary className="cursor-pointer font-semibold text-muted">Changes to the draft ({v.log.length})</summary>
            <ol className="mt-2 space-y-1.5">{[...v.log].reverse().map((l, k) => <li key={k}>{l.text}<span className="block text-[11px] text-muted">{l.by} · {ago(now - l.t)}</span></li>)}</ol>
          </details>
        )}
        <p className="mt-3 text-[11px] text-muted">Demo: SHERPA&apos;s review is simulated from the record and the guidelines.</p>
      </Card>
    </section>
  );
}

function TipRow({ t, canEdit, go, apply, dismiss }: { t: Tip; canEdit: boolean; go: (key: string) => void; apply: () => void; dismiss: () => void }) {
  return (
    <li className={`rounded-xl border p-3 text-[13px] ${t.level === "risk" ? "border-amber-200 bg-amber-50/60" : "border-line"}`}>
      <div className="flex items-start gap-2"><span className={t.level === "risk" ? "text-amber-600" : "text-brand"}><Icon n={t.level === "risk" ? "warn" : "sparkle"} s={14} /></span>
        <span className="flex-1"><b className="font-semibold">{t.text}</b><span className="mt-0.5 block text-muted">{t.why}</span></span></div>
      <div className="mt-2 flex flex-wrap gap-3 pl-6 text-[12px] font-semibold">
        {canEdit && t.fix && <button onClick={apply} className="text-brand">{"toggle" in t.fix ? "Add it" : "Apply fix"}</button>}
        {t.section && <button onClick={() => go(t.section!)} className="text-ink">Show me</button>}
        {canEdit && <button onClick={dismiss} className="text-muted">Dismiss</button>}
      </div>
    </li>
  );
}

function RewriteMenu({ onPick }: { onPick: (m: keyof typeof REWRITES) => void }) {
  const [open, setOpen] = useState(false);
  return (
    <span className="relative">
      <button onClick={() => setOpen(!open)} className="inline-flex items-center gap-1"><Icon n="sparkle" s={12} /> Rewrite</button>
      {open && (
        <span className="absolute right-0 top-6 z-20 flex w-40 flex-col rounded-lg border border-line bg-white p-1 text-[12.5px] font-medium text-ink shadow-lg">
          {(Object.keys(REWRITES) as (keyof typeof REWRITES)[]).map((m) => <button key={m} onClick={() => { setOpen(false); onPick(m); }} className="rounded px-2 py-1.5 text-left hover:bg-surface">{REWRITES[m]}</button>)}
        </span>
      )}
    </span>
  );
}
